/** Builds the shadcn manifests and the embedded registry from item fragments. */
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, posix } from "node:path";
import interfaceCatalog from "../catalog/interface.json";
import { checkRegistryCatalog, checkRegistryTheme, externalRegistryItem } from "../src/design/registry-lint.ts";
import type { EmbeddedRegistry, Registry, RegistryItem } from "../src/design/registry.ts";

type Framework = keyof EmbeddedRegistry;
type FragmentItem = Omit<RegistryItem, "files"> & {
  files: Omit<RegistryItem["files"][number], "content">[];
};

const root = join(import.meta.dir, "..");
const problems: string[] = [];
const catalogIds = new Set(interfaceCatalog.entries.map(({ id }) => id));

function compare(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

function collect(framework: Framework) {
  const directory = `registry/${framework}/items`;
  const fragments = readdirSync(join(root, directory)).filter((name) => name.endsWith(".json")).sort(compare);
  const items = new Map<string, { path: string; item: FragmentItem }>();
  for (const fragment of fragments) {
    const path = `${directory}/${fragment}`;
    const fragmentItems: FragmentItem[] = JSON.parse(readFileSync(join(root, path), "utf8"));
    if (!Array.isArray(fragmentItems)) throw new Error(`${path}: expected an array of items.`);
    for (const item of fragmentItems.sort((a, b) => compare(a.name, b.name))) {
      const previous = items.get(item.name);
      if (previous) problems.push(`${path}: duplicate item "${item.name}" (also in ${previous.path}).`);
      else items.set(item.name, { path, item });
    }
  }

  const visited = new Set<string>();
  const visiting = new Set<string>();
  function validateDependencies(name: string): void {
    if (visited.has(name)) return;
    const { path, item } = items.get(name)!;
    if (visiting.has(name)) {
      problems.push(`${path}: cyclic dependencies: ${[...visiting, name].join(" -> ")}.`);
      return;
    }
    visiting.add(name);
    for (const dependency of item.registryDependencies) {
      if (externalRegistryItem(dependency) !== undefined) continue;
      if (items.has(dependency)) validateDependencies(dependency);
      else problems.push(`${path}: ${name}: unknown ${framework} registry dependency "${dependency}".`);
    }
    visiting.delete(name);
    visited.add(name);
  }

  const embedded: RegistryItem[] = [];
  for (const { path, item } of items.values()) {
    validateDependencies(item.name);
    problems.push(...checkRegistryCatalog([{ ...item, path }], catalogIds));
    const files = item.files.map((file) => {
      const source = join(root, file.path);
      if (
        !/^registry\/(shared|react|astro)\//.test(file.path) ||
        posix.normalize(file.path) !== file.path ||
        file.path.includes("\\") ||
        !statSync(source, { throwIfNoEntry: false })?.isFile()
      ) {
        problems.push(`${path}: ${item.name}: invalid or missing source file "${file.path}".`);
        return { ...file, content: "" };
      }
      return { ...file, content: readFileSync(source, "utf8") };
    });
    embedded.push({ ...item, files });
  }
  const metadata = {
    $schema: "https://ui.shadcn.com/schema/registry.json",
    name: `designfy-${framework}`,
    homepage: "https://github.com/promovaweb/designfy",
  };
  const manifest = {
    $schema: metadata.$schema,
    $comment: "Generated by scripts/embed-registry.ts. Edit the fragments in items/.",
    name: metadata.name,
    homepage: metadata.homepage,
    items: [...items.values()].map(({ item }) => item),
  };
  const registry: Registry = { ...metadata, items: embedded };
  return { manifest, registry };
}

const react = collect("react");
const astro = collect("astro");
const registry: EmbeddedRegistry = { react: react.registry, astro: astro.registry };
const files = new Map(Object.values(registry).flatMap(({ items }) =>
  items.flatMap((item) => item.files.map((file) => [file.path, file] as const)),
));
problems.push(...checkRegistryTheme([...files.values()]));
if (problems.length) {
  process.stderr.write(`Registry validation failed:\n${problems.map((problem) => `- ${problem}`).join("\n")}\n`);
  process.exit(1);
}

const json = JSON.stringify(registry, (_key, value: unknown) => {
  if (!value || typeof value !== "object" || Array.isArray(value)) return value;
  return Object.fromEntries(Object.entries(value).sort(([a], [b]) => compare(a, b)));
}, 2);
const outputs = {
  "registry/react/registry.json": JSON.stringify(react.manifest, null, 2) + "\n",
  "registry/astro/registry.json": JSON.stringify(astro.manifest, null, 2) + "\n",
  "src/generated/registry.ts":
    '/** Embedded registry. Generated by scripts/embed-registry.ts. */\n' +
    'import type { EmbeddedRegistry } from "../design/registry.ts";\n\n' +
    `export const REGISTRY: EmbeddedRegistry = ${json};\n`,
};

for (const [file, content] of Object.entries(outputs)) {
  const path = join(root, file);
  if (!process.argv.includes("--check")) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  } else if (!existsSync(path) || readFileSync(path, "utf8") !== content) {
    process.stderr.write(`${file} is out of date. Run bun run registry:embed.\n`);
    process.exitCode = 1;
  }
}
